/**
 * migrate-featured.ts — 精选故事迁移脚本
 *
 * 从 content/featured-stories.manifest.json 生成 featured_stories INSERT SQL。
 * 输出 SQL 到 stdout（可通过 wrangler d1 execute 导入），或 --dry-run 预览。
 *
 * Usage:
 *   npx tsx scripts/migrate-featured.ts > drizzle/seed-featured.sql
 *   npx tsx scripts/migrate-featured.ts --dry-run
 *   wrangler d1 execute infiplot-db --file=drizzle/seed-featured.sql
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";

const DRY_RUN = process.argv.includes("--dry-run");

type FeaturedTemplate = {
  id: string;
  gender: "男性向" | "女性向";
  index: number;
  title: string;
  outline: string;
  style: string;
  tags: string[];
  coverPath: string;
  firstActPath: string;
  firstScenePath: string;
  active?: boolean;
};

type FeaturedManifest = {
  templates: FeaturedTemplate[];
  displayOrder: Record<string, string[]>;
};

function loadManifest(): FeaturedManifest {
  const path = join(process.cwd(), "content/featured-stories.manifest.json");
  return JSON.parse(readFileSync(path, "utf-8")) as FeaturedManifest;
}

// ── Generate SQL ─────────────────────────────────────────────────────────

function escSql(s: string): string {
  return s.replace(/'/g, "''");
}

function generateSql(): string {
  const manifest = loadManifest();
  const activeTemplates = manifest.templates.filter((template) => template.active !== false);
  const sortOrderById = new Map<string, number>();

  for (const ids of Object.values(manifest.displayOrder)) {
    ids.forEach((id, sortPos) => {
      if (!sortOrderById.has(id)) sortOrderById.set(id, sortPos);
    });
  }

  const lines: string[] = [
    "-- Auto-generated by scripts/migrate-featured.ts",
    "-- Idempotent: uses INSERT OR REPLACE",
    "",
    "DELETE FROM featured_stories;",
    "",
  ];

  const genderMap: Record<string, string> = { "男性向": "male", "女性向": "female" };

  for (const template of activeTemplates) {
    const gender = genderMap[template.gender]!;
    const sortOrder = sortOrderById.get(template.id) ?? template.index;
    const tagsJson = JSON.stringify(template.tags);

    lines.push(
      `INSERT OR REPLACE INTO featured_stories (id, gender, title, outline, style, tags, cover_path, firstact_path, firstscene_path, sort_order, is_active, click_count, created_at)` +
      ` VALUES ('${escSql(template.id)}', '${gender}', '${escSql(template.title)}', '${escSql(template.outline)}', '${escSql(template.style)}', '${escSql(tagsJson)}', '${escSql(template.coverPath)}', '${escSql(template.firstActPath)}', '${escSql(template.firstScenePath)}', ${sortOrder}, 1, 0, unixepoch());`,
    );
  }
  lines.push("");

  return lines.join("\n");
}

// ── Main ─────────────────────────────────────────────────────────────────

try {
  const sql = generateSql();

  if (DRY_RUN) {
    console.log("=== DRY RUN — SQL preview (not executing) ===\n");
    console.log(sql);
    console.log("\n=== END DRY RUN ===");
    console.log(`\nTotal: ${sql.split("INSERT").length - 1} records`);
  } else {
    process.stdout.write(sql);
  }
} catch (err) {
  console.error("Migration script failed:", err instanceof Error ? err.message : err);
  process.exit(1);
}
